#!/usr/bin/env python3
"""Triage the recovered-partial ledger rows: writes notes/partials_triage.md.

A row is "absent" when no definition or call of its method name appears in its source files (the function has no
code yet), "named" when the name appears (a body exists but is incomplete, a stand-in or unverified), "thunk" for
compiler thunks (they follow their target). Groups that are partial by design are listed separately."""
import collections, csv, os, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
BY_DESIGN = {
    "src/rz/COMDirectors.h": "generated creators build classes through the DirectorMake registry instead of calling the "
                             "constructors (keeps the link graph loose); an architecture choice",
    "src/gz/ColorConversion.cpp": "cGZGraphicSystem driver/surface management replaced by the Metal backend",
}


def main() -> None:
    rows = [r for r in csv.DictReader(open(ROOT / "notes/ledger.csv")) if r["status"] == "recovered-partial"]
    cache = {}

    def text(paths):
        out = ""
        for p in paths:
            if p not in cache:
                full = ROOT / p
                cache[p] = full.read_text(errors="replace") if full.exists() else ""
            out += cache[p]
        return out

    per = collections.defaultdict(collections.Counter)
    for r in rows:
        base = r["source"].split("|")[0]
        stem = base.rsplit(".", 1)[0]
        paths = [base] + [stem + "." + e for e in r["source"].split("|")[1:]]
        method = r["symbol"].split("(")[0].rpartition("::")[2].replace("~", "")
        if r["symbol"].startswith(("non-virtual thunk", "virtual thunk")):
            kind = "thunk"
        elif method and re.search(r"\b" + re.escape(method) + r"\s*\(", text(paths)):
            kind = "named"
        else:
            kind = "absent"
        per[base][kind] += 1

    total = collections.Counter()
    for c in per.values():
        total.update(c)
    out = ["# Partial rows triage", "", "Generated by `scripts/partials_triage.py`; do not edit by hand.", "",
           f"{len(rows):,} `recovered-partial` rows: {total['absent']:,} with no code (absent), {total['named']:,} with "
           f"a body that is incomplete or unverified (named), {total['thunk']:,} thunks.", "",
           "## Partial by design", ""]
    out += [f"- `{f}` ({sum(per[f].values())} rows): {why}" for f, why in BY_DESIGN.items() if f in per]
    out += ["", "## Work list", "", "| Source | Rows | absent | named | thunk |", "|---|---:|---:|---:|---:|"]
    for f, c in sorted(per.items(), key=lambda kv: -sum(kv[1].values())):
        if f in BY_DESIGN:
            continue
        out.append(f"| `{f}` | {sum(c.values())} | {c['absent']} | {c['named']} | {c['thunk']} |")
    (ROOT / "notes/partials_triage.md").write_text("\n".join(out) + "\n")
    print(f"notes/partials_triage.md: {len(rows)} partial rows in {len(per)} files")


if __name__ == "__main__":
    main()
