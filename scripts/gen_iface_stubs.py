#!/usr/bin/env python3
"""Generates default-returning test stubs for abstract interfaces: gen_iface_stubs.py <out.h> <header:Class> ...
Every pure virtual of Class (declared in header) gets an override returning a value-initialised result, so a
test can derive from `Class##Stub` and override only what it records. Destructors and cIGZUnknown slots are
left to the stub's trivial refcounting."""
import re, sys, pathlib

def methods(text, cls):
    m = re.search(r'class\s+%s\b[^{]*\{(.*?)\n\};' % re.escape(cls), text, re.S)
    body = m.group(1)
    body = re.sub(r'//[^\n]*', '', body)
    body = re.sub(r'\s+', ' ', body)
    out = []
    for decl in re.findall(r'virtual\s+(.+?)\s*=\s*0\s*;', body):
        mm = re.match(r'(.+?)\s*\b(\w+)\s*\((.*)\)\s*(const)?$', decl)
        if not mm or mm.group(2).startswith('~'):
            continue
        out.append((mm.group(1).strip(), mm.group(2), mm.group(3).strip(), bool(mm.group(4))))
    return out

def main():
    out = pathlib.Path(sys.argv[1]); lines = ['// generated by scripts/gen_iface_stubs.py - do not edit', '#pragma once']
    includes = []
    stubs = []
    for spec in sys.argv[2:]:
        hdr, cls = spec.split(':')
        includes.append(hdr)
        text = pathlib.Path('src/' + hdr).read_text()
        body = []
        seen = set()
        for ret, name, args, const in methods(text, cls):
            sig = (name, args)
            ret_clean = ret
            default = '' if ret_clean == 'void' else ' return {};'
            body.append('    %s %s(%s)%s override {%s }' % (ret_clean, name, args, ' const' if const else '', default))
        stubs.append('class %sStub : public %s {\npublic:\n    std::uint32_t AddRef() override { return ++refs_; }\n    std::uint32_t Release() override { return --refs_; }\n    bool QueryInterface(std::uint32_t, void**) override { return false; }\n%s\n    std::uint32_t refs_ = 1;\n};' % (cls, cls, '\n'.join(body)))
    lines += ['#include "%s"' % h for h in includes] + ['']
    lines += stubs
    out.write_text('\n'.join(lines) + '\n')

main()
