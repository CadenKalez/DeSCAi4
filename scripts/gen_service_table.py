#!/usr/bin/env python3
"""Generates src/app/ServiceTable.inc (every SL:: pointer of ServiceLocator.h with its boot phase) and docs/WIRING.md
(which Set*Host seams the native application installs, which only a generated stub installs, and which nothing installs).
Usage: scripts/gen_service_table.py"""
import re, pathlib, collections
root = pathlib.Path(__file__).resolve().parent.parent
header = (root / "src/sc4/ServiceLocator.h").read_text()

names = []
for m in re.finditer(r"^extern\s+[^;]*;", header, re.M):
    stmt = m.group(0)
    for n in re.findall(r"\*?\s*(sp[A-Za-z0-9]+)\b", stmt):
        if n not in names: names.append(n)

# the boot phase each pointer is bound in (the locator's OnAppCreate / OnAppInit1 / OnAppInit2, then the city load)
required_boot = {"spSC4", "spRM", "spMS2", "spPreferences"}
boot = {"spSC4", "spPreferences", "spCCM", "spCommandServer", "spRenderProperties", "spGF", "spStringDetokenizer", "spWinLocationSaver",
        "spGlyphTextureManager", "spLua", "spGS", "spGS2", "spGDriver", "spFeatureManager", "spRDD", "spSS", "spTextureBindingFactory",
        "spRM", "spMS", "spMS2", "spWinSC4App", "sp24HourClock"}
view = {"spView3D", "spView3DWin", "spModelMaker", "spRenderer", "spViewUtilities", "spTerrainView"}
lines = ["// Generated by scripts/gen_service_table.py from ServiceLocator.h; do not edit.",
         "// {name, pointer slot, phase (0 boot, 1 city load, 2 view), required at boot}"]
for n in names:
    phase = 0 if n in boot else (2 if n in view else 1)
    req = "true" if n in required_boot else "false"
    if n == "spPreferences":
        slot = "reinterpret_cast<const void* const*>(&SL::spPreferences)"
    else:
        slot = f"reinterpret_cast<const void* const*>(&SL::{n})"
    lines.append(f'{{"SL::{n}", {slot}, {phase}, {req}}},')
(root / "src/app/ServiceTable.inc").write_text("\n".join(lines) + "\n")

# hosts
decl = collections.OrderedDict()
for p in list((root / "src").rglob("*.h")):
    t = p.read_text(errors="ignore")
    for m in re.finditer(r"\bvoid\s+(Set[A-Za-z0-9_]*Host)\s*\(", t):
        decl.setdefault(m.group(1), str(p.relative_to(root)))
native, stub, other = collections.defaultdict(set), collections.defaultdict(set), collections.defaultdict(set)
for p in list((root / "src").rglob("*.cpp")) + list((root / "src").rglob("*.mm")):
    rel = str(p.relative_to(root))
    t = p.read_text(errors="ignore")
    for name in decl:
        if re.search(r"\b" + name + r"\s*\(", t) and not re.search(r"void\s+" + name + r"\s*\(", t):
            if "/hosts/" in rel: stub[name].add(rel)
            elif rel.startswith("src/app/"): native[name].add(rel)
            else: other[name].add(rel)
out = ["# Runtime wiring (generated by scripts/gen_service_table.py)", "",
       "Every recovered class reaches the engine through a `Set*Host` seam. `native` means a hand-written adapter in `src/app`, `stub` means only the",
       "generated neutral host (`src/app/hosts`) installs it (the class runs without its neighbours), `none` means nothing installs it.", "",
       f"- native: {sum(1 for n in decl if n in native)}   stub only: {sum(1 for n in decl if n not in native and n in stub)}   none: {sum(1 for n in decl if n not in native and n not in stub)}", "",
       "| seam | declared in | status | installed by |", "|---|---|---|---|"]
for n, h in decl.items():
    if n in native: st, by = "native", ", ".join(sorted(native[n]))
    elif n in stub: st, by = "stub", ", ".join(sorted(stub[n]))
    else: st, by = "none", ", ".join(sorted(other[n])) if n in other else ""
    out.append(f"| {n} | {h} | {st} | {by} |")
(root / "docs").mkdir(exist_ok=True)
(root / "docs/WIRING.md").write_text("\n".join(out) + "\n")
print(len(names), "service pointers;", len(decl), "host seams")
