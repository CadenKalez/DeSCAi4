#!/usr/bin/env python3
"""Scans the port for stand-ins that must be replaced by recovered code and writes notes/STUB_SCAN.md.

Kinds:
  host stub     src/app/hosts/Stub*.cpp (generated by gen_stub_hosts.py): a neutral implementation of a recovered host interface,
                installed by NativeCityHosts.cpp so a city file can load. Replaced by a real adapter over the recovered class.
  iface stub    src/app/hosts/Iface*.cpp (generated by gen_stub_iface.py): a neutral host for a class built with a host argument.
  code stub     a function in a recovered class that is an empty / placeholder body (PARTIAL stub, unrecovered (stub), NOT RECOVERED ...).
  app stub      stubs written by hand in src/app, src/tools, src/render ... for the native build.
For each host stub the owning header's classes are looked up in notes/ledger.csv: how many functions are still not `recovered`."""
import csv, collections, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
hosts = sorted((ROOT / "src/app/hosts").glob("*.cpp"))

# ledger: source file -> [total, not recovered]
led = collections.defaultdict(lambda: [0, 0])
for r in csv.DictReader((ROOT / "notes/ledger.csv").open()):
    for src in re.findall(r"src/[\w/]+?\.(?:cpp|h)", r["source"].replace("|h", ".h").replace(".cpp.h", ".cpp")):
        led[pathlib.Path(src).stem][0] += 1
        if r["status"] != "recovered": led[pathlib.Path(src).stem][1] += 1

rows = []
for p in hosts:
    text = p.read_text()
    m = re.search(r'struct\s+(\w+)\s+final\s*:\s*(?:\w+::)?(I\w+)', text)
    inc = re.search(r'#include\s+"sc4/(\w+)\.h"', text) or re.search(r'#include\s+"(?:[\w]+/)?(\w+)\.h"', text)
    methods = len(re.findall(r'\boverride\b', text))
    header = inc.group(1) if inc else "?"
    total, open_ = led.get(header, [0, 0])
    kind = "iface" if p.name.startswith("Iface") else "host"
    rows.append((kind, p.name, m.group(2) if m else "?", header, methods, total, open_))

code_stub_markers = re.compile(r"PARTIAL stub|unrecovered \(stub\)|NOT RECOVERED|empty stubs?\b|stubbed so")
empty_override = re.compile(r"override\s*\{\s*(?:return\s*(?:\{\}|false|true|nullptr|0|0\.0f)\s*;)?\s*\}")
code = []
empties = []
for p in sorted((ROOT / "src/app").glob("*")) + sorted((ROOT / "src/tools").glob("*")):
    if p.suffix in (".cpp", ".mm", ".h"):
        n = len(empty_override.findall(p.read_text(errors="ignore")))
        if n >= 5: empties.append((str(p.relative_to(ROOT)), n))
for p in sorted((ROOT / "src").rglob("*")):
    if p.suffix not in (".cpp", ".h", ".mm", ".inc") or "src/app/hosts" in str(p): continue
    t = p.read_text(errors="ignore")
    n = len(code_stub_markers.findall(t))
    if n: code.append((str(p.relative_to(ROOT)), n))

out = ["# Stub scan", "", "Generated by `scripts/stub_scan.py`. Each stub below stands in for code that is not recovered, or recovered but not wired.", ""]
hostrows = [r for r in rows if r[0] == "host"]
ifacerows = [r for r in rows if r[0] == "iface"]
ready = [r for r in hostrows if r[5] and r[6] == 0]
out += [f"* host stubs (src/app/hosts/Stub*.cpp): **{len(hostrows)}** files", f"* iface stubs (src/app/hosts/Iface*.cpp): **{len(ifacerows)}** files",
        f"* files with placeholder code inside recovered classes (PARTIAL stub / unrecovered / NOT RECOVERED / empty stub): **{len(code)}**",
        f"* hand-written app files with 5 or more empty-bodied host overrides: **{len(empties)}** ({sum(n for _, n in empties)} overrides)",
        f"* host stubs whose owning header is fully recovered (a real adapter can replace them now): **{len(ready)}**", ""]
out += ["## Host stubs", "", "| stub file | interface | owning header | methods | header functions | not recovered |", "|---|---|---|---:|---:|---:|"]
for r in sorted(hostrows, key=lambda r: (r[6] > 0, r[6], r[1])):
    out.append(f"| {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} |")
out += ["", "## Iface stubs", "", "| file | interface | owning header | methods |", "|---|---|---|---:|"]
for r in ifacerows: out.append(f"| {r[1]} | {r[2]} | {r[3]} | {r[4]} |")
out += ["", "## App files with empty-bodied host overrides (hand-written stand-ins)", "", "| file | empty overrides |", "|---|---:|"]
for f, n in sorted(empties, key=lambda x: -x[1]): out.append(f"| {f} | {n} |")
out += ["", "## Placeholder code in other files", "", "| file | markers |", "|---|---:|"]
for f, n in sorted(code, key=lambda x: -x[1]): out.append(f"| {f} | {n} |")
(ROOT / "notes/STUB_SCAN.md").write_text("\n".join(out) + "\n")
print(f"app files with empty overrides {len(empties)} | host stubs {len(hostrows)} | iface stubs {len(ifacerows)} | placeholder files {len(code)} | host stubs with a fully recovered header {len(ready)}")
