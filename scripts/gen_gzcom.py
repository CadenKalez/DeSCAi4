#!/usr/bin/env python3
"""Generate src/gz/GZCOM.{h,cpp} and the creator translation units from the decompiled GZCOM_Create* /
GZCOM_c*CLSID functions (work/t/gzcom_dec.txt via scripts/dec_addrs.py; creator-capable classes in
work/t/gzcom_ok.json). The generated files are committed; this script documents how they were made."""
import json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
txt = (ROOT/"work/t/gzcom_dec.txt").read_text()
ok = {k: h for k, h in json.load(open(ROOT/"work/t/gzcom_ok.json"))}
# creators added later live in GZCOMCreators2.cpp / GZCOMCreators3.cpp (generated by hand-run helper, see git log)
LATER = set(open(ROOT/"scripts/gzcom_later.txt").read().split()) if (ROOT/"scripts/gzcom_later.txt").exists() else set()
# one translation unit per creator, in src/gz/gzcom_creators/<class>.cpp (their headers cannot share a TU)
CREATORS = set(open(ROOT/"scripts/gzcom_creators.txt").read().split()) if (ROOT/"scripts/gzcom_creators.txt").exists() else set()
clsid, create = {}, {}
for b in re.split(r"^//==== ", txt, flags=re.M)[1:]:
    head, _, body = b.partition("\n")
    addr, _, name = head.partition(" ")
    name = name.strip()
    m = re.match(r"GZCOM_(c\w+)CLSID\(\)", name)
    if m:
        clsid[m.group(1)] = (addr, int(re.search(r"return (0x[0-9a-fA-F]+);", body).group(1), 16)); continue
    m = re.match(r"GZCOM_Create(c\w+)\(\)", name)
    if m:
        s = re.search(r"operator_new\((0x[0-9a-fA-F]+|\d+)\)", body)
        create[m.group(1)] = (addr, int(s.group(1), 0) if s else 0)
classes = sorted(clsid, key=lambda k: int(clsid[k][0], 16))
H = ["// Generated by scripts/gen_gzcom.py — the GZCOM class-factory pairs of the game executable.",
     "// Every class has GZCOM_Create<class>() (allocate + construct, returning the primary object pointer) and",
     "// GZCOM_<class>CLSID() (the class id the COM director registers it under). Creators of classes that are not",
     "// recovered yet return nullptr; allocSize is the size the original allocates (0 = class-specific allocator).",
     "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
     "namespace sc4 {", "class ICityHost;", "}  // namespace sc4", "",
     "namespace gzcom {", "",
     "// The city's host services. The application installs them; the city creator translation unit registers the",
     "// constructor-backed factory (GZCOM_CreatecSC4City stays a weak fallback so GZCOMCreators7.cpp can override it).",
     "void SetCityHost(sc4::ICityHost* host);", "sc4::ICityHost* CityHost();", "void SetCityCreator(void* (*creator)());", "",
     "struct ClassFactoryInfo {", "    const char* className;", "    std::uint32_t clsid;", "    std::uint32_t allocSize;",
     "    void* (*create)();", "};", ""]
for k in classes:
    H.append(f"constexpr std::uint32_t kCLSID_{k} = 0x{clsid[k][1]:08x};")
H.append("")
for k in classes:
    H.append(f"std::uint32_t GZCOM_{k}CLSID();")
    H.append(f"void* GZCOM_Create{k}();")
H += ["", "extern const ClassFactoryInfo kClassFactories[];", "extern const std::size_t kClassFactoryCount;",
      "const ClassFactoryInfo* FindClassFactory(std::uint32_t clsid);", "", "}  // namespace gzcom", ""]
(ROOT/"src/gz/GZCOM.h").write_text("\n".join(H))
C = ['// Generated by scripts/gen_gzcom.py (see GZCOM.h).', '#include "gz/GZCOM.h"', '', 'namespace gzcom {', '',
     'namespace {', 'sc4::ICityHost* s_cityHost = nullptr;', 'void* (*s_cityCreator)() = nullptr;', '}  // namespace', '',
     'void SetCityHost(sc4::ICityHost* host) { s_cityHost = host; }',
     'sc4::ICityHost* CityHost() { return s_cityHost; }',
     'void SetCityCreator(void* (*creator)()) { s_cityCreator = creator; }', '']
for k in classes:
    C.append(f"std::uint32_t GZCOM_{k}CLSID() {{ return kCLSID_{k}; }}")
C.append("")
for k in classes:
    if k == "cSC4City":
        C.append("// weak fallback: gzcom_creators/cSC4City.cpp registers the real constructor-backed creator (it needs the city host)")
        C.append("__attribute__((weak)) void* GZCOM_CreatecSC4City() { return s_cityCreator ? s_cityCreator() : nullptr; }")
    elif k in CREATORS:
        C.append(f"// weak fallback: gzcom_creators/{k}.cpp provides the real constructor-backed creator when linked")
        C.append(f"__attribute__((weak)) void* GZCOM_Create{k}() {{ return nullptr; }}")
    elif k not in ok and k not in LATER:
        C.append(f"// original allocates {create[k][1]:#x} bytes; the class is not recovered yet")
        C.append(f"void* GZCOM_Create{k}() {{ return nullptr; }}")
    else:
        C.append(f"// weak fallback: GZCOMCreators*.cpp provide the real constructor-backed creator when linked")
        C.append(f"__attribute__((weak)) void* GZCOM_Create{k}() {{ return nullptr; }}")
C += ["", "const ClassFactoryInfo kClassFactories[] = {"]
for k in classes:
    C.append(f'    {{"{k}", kCLSID_{k}, {create[k][1]:#x}, &GZCOM_Create{k}}},')
C += ["};", "const std::size_t kClassFactoryCount = sizeof(kClassFactories) / sizeof(kClassFactories[0]);", "",
      "const ClassFactoryInfo* FindClassFactory(std::uint32_t clsid) {",
      "    for (std::size_t i = 0; i < kClassFactoryCount; ++i)",
      "        if (kClassFactories[i].clsid == clsid) return &kClassFactories[i];",
      "    return nullptr;", "}", "", "}  // namespace gzcom", ""]
(ROOT/"src/gz/GZCOM.cpp").write_text("\n".join(C))
def creators(path, names):
    hs = sorted({ok[k] for k in names})
    L = ["// Generated by scripts/gen_gzcom.py: GZCOM creators of the recovered classes.", '#include "gz/GZCOM.h"', ""]
    L += [f'#include "{h}"' for h in hs]
    L += ["", "namespace gzcom {", ""]
    for k in names:
        L.append(f"void* GZCOM_Create{k}() {{ return static_cast<void*>(new sc4::{k}()); }}")
    L += ["", "}  // namespace gzcom", ""]
    (ROOT/path).write_text("\n".join(L))
names = [k for k in classes if k in ok]
creators("src/gz/GZCOMCreators.cpp", [k for k in names if k != "cSC4LotConfigurationManager"])
creators("src/gz/GZCOMCreatorsLotConfig.cpp", ["cSC4LotConfigurationManager"])
print(len(classes), len(names))
