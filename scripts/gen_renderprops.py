#!/usr/bin/env python3
"""Generate src/sc4/RenderPropertyDefaults.inc from the cRegk* constructors of cSC4RenderProperties::cProperties.
Order = call order in cProperties::cProperties(); names from the ctors' string literals (disassembly), values from
the decompile. Needs /tmp/sc4.asm (otool -arch x86_64 -tV of the game binary) and work/sc4/*cRegk*.txt."""
import re, struct, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
asm = open("/tmp/sc4.asm").read().splitlines()
def func_asm(start_hex):
    out, on = [], False
    for l in asm:
        if l.startswith(start_hex + "\t"): on = True
        elif on and re.match(r"^[0-9a-f]{16}\t", l) is False: pass
        if on:
            out.append(l)
            if l.endswith("retq") or "\tretq" in l: break
    return out
# order of constructors
syms = {}
for line in (ROOT/"notes/symbols-functions-demangled.txt").read_text(errors="replace").splitlines():
    a, _, n = line.partition(" ")
    syms[n] = a
cprops = func_asm("000000010028db18")
order = []
for l in cprops:
    m = re.search(r"## cSC4RenderProperties::cProperties::(cRegk\w+)::", l)
    if m: order.append(m.group(1))
entries = []
for name in order:
    addr = syms[f"cSC4RenderProperties::cProperties::{name}::{name}()"]
    body = func_asm(addr)
    lit = next(re.search(r'literal pool for: "([^"]*)"', l).group(1) for l in body if "literal pool for" in l)
    kind = "bool" if any("m_boolProperties" in l for l in body) else "int" if any("m_intProperties" in l for l in body) else "float"
    txt = (ROOT/f"work/sc4/cSC4RenderProperties_cProperties_{name}.txt").read_text()
    pre = txt.split("std::string::assign")[0]
    post = txt.split("std::string::assign", 1)[1].split("if (DAT_")[0]
    ids = re.findall(r"local_\w+\[0\] = (0x[0-9a-fA-F]+|\d+);", pre)
    vals = re.findall(r"local_\w+ = (0x[0-9a-fA-F]+|\d+);", post)
    entries.append((name, lit, kind, int(ids[-1], 0), [int(v, 0) for v in vals]))
with open(ROOT/"src/sc4/RenderPropertyDefaults.inc", "w") as f:
    f.write("// Generated by scripts/gen_renderprops.py from the cRegk* constructors of cSC4RenderProperties::cProperties\n")
    f.write("// (call order = property index). Fields: registry key name, id, then kind specific defaults.\n")
    for name, lit, kind, pid, vals in entries:
        if kind == "bool":
            v = vals[0] if vals else 0
            b2 = vals[1] if len(vals) > 1 else 0
            f.write(f'RP_BOOL("{lit}", {pid}, {v & 0xff}, {(v >> 8) & 0xff}, {b2 & 0xff})\n')
        else:
            v = vals[0] if vals else 0
            c = vals[1] if len(vals) > 1 else 0
            lo, hi = v & 0xffffffff, (v >> 32) & 0xffffffff
            f.write(f'RP_{kind.upper()}("{lit}", {pid}, 0x{lo:08x}u, 0x{hi:08x}u, 0x{c & 0xffffffff:08x}u)\n')
print(len(entries), "entries", sum(1 for e in entries if e[2]=="bool"), "bool")
