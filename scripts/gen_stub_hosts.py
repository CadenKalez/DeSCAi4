#!/usr/bin/env python3
"""Generates src/app/NativeCityHosts.cpp: a neutral stub for every recovered host interface (IxxxHost with a SetxxxHost
setter), installed once so a city file's Read paths can run. Usage: gen_stub_hosts.py [--skip Name,Name] [--only Name,...]"""
import re, sys, glob, os
skip = set("Terrain Region Nation SplashScreen SLString SLBuffer Dispatch Detokenizer RegionalCity RegionScreen RegionView RegionScroll RegionClouds Host View3DWin Render3D Simulator ControllerManager DemandSimulator Aura GrowthDeveloper LandfillDeveloper CivicBuilding TractDeveloper".split())
only = None
for i, a in enumerate(sys.argv):
    if a == '--skip': skip |= set(sys.argv[i+1].split(','))
    if a == '--only': only = set(sys.argv[i+1].split(','))
def strip(t):
    t = re.sub(r'//[^\n]*', '', t); return re.sub(r'/\*.*?\*/', '', t, flags=re.S)
heads = {p: strip(open(p).read()) for p in glob.glob('src/sc4/*.h')}
out_inc, out_cls, out_inst, done = set(), [], [], []
for p, t in sorted(heads.items()):
    for m in re.finditer(r'void\s+Set(\w+?)Host\(\s*(?:sc4::)?(I\w+)\s*\*\s*\w*\s*\)', t):
        name, iface = m.group(1), m.group(2)
        if name in skip or (only and name not in only) or iface in done: continue
        # find the interface body in any header
        body = None; hp = None
        for q, u in heads.items():
            b = re.search(r'(?:class|struct)\s+' + iface + r'\s*(?::\s*public\s+[\w:]+\s*)?\{', u)
            if b:
                i = b.end(); d = 1
                while d and i < len(u):
                    d += (u[i] == '{') - (u[i] == '}'); i += 1
                body, hp = u[b.end():i-1], q; break
        if body is None: continue
        meths = []
        for pm in re.finditer(r'virtual\s+([^;{}()]+?)\s*\b(\w+)\s*\(([^;{}]*?)\)\s*(const)?\s*=\s*0\s*;', body, re.S):
            ret, mn, args, cst = pm.group(1).strip(), pm.group(2), ' '.join(pm.group(3).split()), pm.group(4) or ''
            if mn.startswith('~'): continue
            meths.append((ret, mn, args, cst))
        sig = []
        for ret, mn, args, cst in meths:
            args2 = re.sub(r'\s*=\s*[^,)]+', '', args)   # drop defaults
            if ret == 'void': ctx = '{}'
            elif ret.endswith('&'):
                base = ret[:-1].replace('const', '').strip()
                ctx = '{ static %s dummy{}; return dummy; }' % base
            else: ctx = '{ return {}; }'
            sig.append('    %s %s(%s)%s override %s' % (ret, mn, args2, ' const' if cst else '', ctx))
        cls = 'Stub' + name
        ns = 'sc4::' if re.search(r'namespace\s+sc4', heads[hp]) else ''
        os.makedirs('src/app/hosts', exist_ok=True)
        with open('src/app/hosts/Stub%s.cpp' % name, 'w') as f:
            f.write('// Generated by scripts/gen_stub_hosts.py: a neutral %s for the city load.\n#include <string>\n#include <vector>\n#include "sc4/%s"\n\nnamespace native {\nnamespace {\nusing namespace sc4;\nstruct %s final : %s {\n%s\n};\n}  // namespace\n\nvoid Install%sStub() { static %s s; %sSet%sHost(&s); }\n\n}  // namespace native\n' % (iface, os.path.basename(hp), cls, iface, '\n'.join(sig), name, cls, ns, name))
        out_inst.append(name)
        done.append(iface)
with open('src/app/hosts/list.txt', 'w') as f: f.write('\n'.join(out_inst) + '\n')
print(len(done), 'hosts')
