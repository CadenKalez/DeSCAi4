#!/usr/bin/env python3
"""Generate src/rz/COMDirectors.{h,cpp}: the table-driven COM directors (constructor = AddDirector/AddCls list,
Create* functions, GetDirectorID, the Get*Director accessors). Parses the decompiles in work/*/<Director>.txt
(run scripts/export_class.py first). Creators build their class through the DirectorMake registry."""
import re, glob, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRS = sys.argv[1:]
GETTERS = {  # director class -> accessor of the original (function-local static instance)
    'cGZWin32COMDirector': 'GetGZWin32COMDllDirector', 'cGZWinCOMDirector': 'GetGZWinCOMDllDirector',
    'cGXCOMDirector': 'GetGimexCOMDllDirector', 'cGZResManCOMDirector': 'GetGZResManCOMDirector',
    'cGZResourceCOMDirectorW32': 'GetGZResourceCOMDirectorW32', 'cGZGraphicCOMDirector': 'GetGZGraphicCOMDllDirector',
    'cGZGraphicWin32COMDirector': 'GetGZGraphicWin32COMDllDirector', 'cGZScriptCOMDirector': 'GetGZScriptCOMDirector',
    'cGZUIScriptCOMDirector': 'GetGZUIScriptCOMDirector', 'cSC4ResourceLibCOMDirector': 'GetSC4ResourceLibCOMDirector',
    'cSC4AutomataCOMDirector': 'SC4AutomataGetCOMDirector', 'cSC4ScriptedWindowCOMDirector': 'SC4GetSC4ScriptedWindowCOMDirector',
    'cFontCOMDirector': 'GetFontComDirector', 'cGZSoundCOMDirector': 'GetGZSoundCOMDirector',
    'cGZDrawCOMDirector': 'GetGZDrawCOMDllDirector', 'cSC4GDriversCOMDirector': 'GetSC4GDriversCOMDirector',
    'cSCLuaCOMDirector': 'GetSCLuaCOMDirector', 'cGZWWWCOMDirector': 'GetGZWWWCOMDllDirector',
    'cGZWWWWin32COMDirector': 'GetGZWWWWin32COMDllDirector', 'cSC4COMDirector': 'SC4GetCOMDirector',
}
KNOWN = {'nSCRes_cFileParser': '0x5cf9459a'}          # GZCOM class ids missing from GZCOM.h
ONSTART = {'cGZWinCOMDirector': [0x84174448, 0xc2c2eb0f], 'cGZToolsCOMDirector': [0x414a2b1]}
H = ['// Generated by scripts/gen_directors.py: the table-driven COM directors.', '#pragma once', '#include "gz/GZCOMDirector.h"   // RZGetCOMDllDirector(), GZCOM()', '#include "rz/cRZCOMDllDirector.h"', '',
     'namespace gz {', '', 'using DirectorMaker = cIGZUnknown* (*)();',
     'void RegisterDirectorMaker(const char* className, DirectorMaker maker);',
     '// The object of the named class, or nullptr when no maker was registered (class not linked in).',
     'cIGZUnknown* DirectorMake(const char* className);', '']
C = ['// Generated by scripts/gen_directors.py.', '#include "rz/COMDirectors.h"', '#include "gz/GZCOM.h"', '#include <map>', '#include <string>', '',
     'namespace gz {', '',
     'static std::map<std::string, DirectorMaker>& Makers() { static std::map<std::string, DirectorMaker> m; return m; }',
     'void RegisterDirectorMaker(const char* className, DirectorMaker maker) { Makers()[className] = maker; }',
     'cIGZUnknown* DirectorMake(const char* className) {',
     '    const auto it = Makers().find(className);',
     '    return it == Makers().end() ? nullptr : it->second();', '}',
     '// cRZCOMDllGenericClassFactoryT<T>::CreateInstance: make a T and hand out the requested interface.',
     'static bool MakeInterface(const char* className, std::uint32_t iid, void** out) {',
     '    cIGZUnknown* object = DirectorMake(className);',
     '    if (!object) return false;',
     '    if (object->QueryInterface(iid, out)) return true;',
     '    object->AddRef();',
     '    object->Release();',
     '    return false;', '}', '']
body_all = []
getter_decls = []
for d in DIRS:
    path = glob.glob(str(ROOT / f"work/*/{d}.txt"))[0]
    txt = open(path).read()
    parts = re.split(r"^//==== (0x[0-9a-f]+)  ", txt, flags=re.M)
    funcs = {}
    for i in range(1, len(parts), 2):
        title = parts[i + 1].split("\n")[0]
        if "non-virtual" in title: continue
        funcs.setdefault(title, parts[i + 1])
    ctor_key = next((k for k in funcs if k.startswith(f"{d}::{d}()")), None)
    ctor = re.sub(r"\s+", " ", funcs[ctor_key]) if ctor_key else ""
    # directors that adopt their children into the process director (`this_00 = RZGetCOMDllDirector()`):
    # AddDirector(process, child) followed by child->OnStart(GZCOM()) for most of them
    root_children = []
    if "this_00 = (cRZCOMDllDirector *)RZGetCOMDllDirector();" in ctor:
        for m in re.finditer(r"pcVar3 = \(cRZCOMDllDirector \*\)(\w+)\(\); cRZCOMDllDirector::AddDirector\(this_00, ?pcVar3\); (\(\*\*\(code \*\*\)\(\*\(long \*\)pcVar3 \+ 0x20\)\)\(pcVar3, ?uVar2\);)?", ctor):
            root_children.append((m.group(1), bool(m.group(2))))
    # ordered events in the constructor: AddDirector(this, <getter>) and AddCls*(this, id, creator)
    events = []
    for m in re.finditer(r"(\w+) = \(cRZCOMDllDirector \*\)(\w+)\(\);|(?:uVar\d = (GZCOM_\w+?)CLSID\(\); )?cRZCOMDllDirector::AddCls\w*\s*\(\s*\(cRZCOMDllDirector \*\)this,\s*(\w+),\s*([\w:<>]+)\s*\)", ctor):
        if m.group(2):
            if not root_children: events.append(("dir", m.group(2)))
        else: events.append(("cls", m.group(3), m.group(4), m.group(5)))
    creators = {}
    for k, v in funcs.items():
        m = re.match(rf"{d}::(Create\w+)\(\)", k)
        if m:
            cm = re.search(r"(\w+)::\1\(this", v) or re.search(r"(\w+)::Construct\(", v)
            creators[m.group(1)] = cm.group(1) if cm else None
    did = re.search(r"return (0x[0-9a-f]+);", next(v for k, v in funcs.items() if "GetDirectorID" in k)).group(1)
    H.append(f"class {d} : public cRZCOMDllDirector {{\npublic:\n    {d}();\n    std::uint32_t GetDirectorID() const override {{ return {did}; }}")
    if d in ONSTART: H.append("    bool OnStart(cIGZCOM* com) override;")
    for name in creators: H.append(f"    static cIGZUnknown* {name}();")
    H.append("};\n")
    body = [f"{d}::{d}() {{"]
    if root_children:
        body.append("    if (cRZCOMDllDirector* process = RZGetCOMDllDirector()) {")
        body.append("        cIGZCOM* com = GZCOM();")
        for getter, onstart in root_children:
            body.append(f"        {{ cRZCOMDllDirector* child = {getter}(); process->AddDirector(child);" + (" child->OnStart(com);" if onstart else "") + " }")
        body.append("    }")
    for ev in events:
        if ev[0] == "dir":
            if ev[1] in G2D if False else False: pass
            body.append(f"    AddDirector({ev[1]}());")
            continue
        _, gz, idv, creator = ev
        if gz:
            cls = gz[len("GZCOM_"):]
            clsid = KNOWN.get(cls, "gzcom::kCLSID_" + cls)
            body.append(f"    AddCls({clsid}, +[]() -> cIGZUnknown* {{ return DirectorMake(\"{cls}\"); }});")
        elif "CreateInstance" in creator:          # cRZCOMDllGenericClassFactoryT<T>::CreateInstance
            cls = re.search(r"<(\w+)>", creator).group(1)
            body.append(f"    AddCls({idv}, +[](std::uint32_t iid, void** out) -> bool {{ return MakeInterface(\"{cls}\", iid, out); }});")
        elif "::" in creator:
            body.append(f"    AddCls({idv}, +[]() -> cIGZUnknown* {{ return DirectorMake(\"{creator.split('::')[0]}\"); }});")
        elif creator in creators:
            body.append(f"    AddCls({idv}, &{d}::{creator});")
        else:
            body.append(f"    AddCls({idv}, +[]() -> cIGZUnknown* {{ return DirectorMake(\"{creator}\"); }});")
    body.append("}")
    body_all += body + [""]
    if d in ONSTART:
        body_all.append(f"bool {d}::OnStart(cIGZCOM* com) {{ return StartServices(com, {{{', '.join(hex(x) for x in ONSTART[d])}}}); }}")
    for name, cls in creators.items():
        body_all.append(f"cIGZUnknown* {d}::{name}() {{ return DirectorMake(\"{cls or name}\"); }}")
    body_all.append("")
    if d in GETTERS:
        getter_decls.append((GETTERS[d], d))
for g, d in getter_decls:
    H.insert(H.index('cIGZUnknown* DirectorMake(const char* className);') + 1, f"cRZCOMDllDirector* {g}();   // the process-wide {d}")
C += body_all
for g, d in getter_decls:
    C.append(f"cRZCOMDllDirector* {g}() {{ static {d} director; return &director; }}")
C += ["", "}  // namespace gz", ""]
H.append("}  // namespace gz\n")
(ROOT / "src/rz/COMDirectors.h").write_text("\n".join(H))
(ROOT / "src/rz/COMDirectors.cpp").write_text("\n".join(C))
