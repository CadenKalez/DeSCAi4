#!/usr/bin/env python3
"""Generate src/rz/COMDirectors.{h,cpp}: the table-driven COM directors (constructor = AddCls list, Create*
functions, GetDirectorID). Parses the decompiles in work/*/<Director>.txt. Creators build their class through
the DirectorMake registry (classes plug in with RegisterDirectorMaker)."""
import re, glob, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRS = sys.argv[1:]
H = ['// Generated by scripts/gen_directors.py: the table-driven COM directors.', '#pragma once', '#include "rz/cRZCOMDllDirector.h"', '',
     'namespace gz {', '',
     '// The singleton the window director adopts (GetGZWin32COMDllDirector).',
     'cRZCOMDllDirector* GetGZWin32COMDllDirector();', '',
     'using DirectorMaker = cIGZUnknown* (*)();',
     'void RegisterDirectorMaker(const char* className, DirectorMaker maker);',
     '// The object of the named class, or nullptr when no maker was registered (class not linked in).',
     'cIGZUnknown* DirectorMake(const char* className);', '']
C = ['// Generated by scripts/gen_directors.py.', '#include "rz/COMDirectors.h"', '#include "gz/GZCOM.h"', '#include <map>', '#include <string>', '', 'namespace gz {', '',
     'static std::map<std::string, DirectorMaker>& Makers() { static std::map<std::string, DirectorMaker> m; return m; }',
     'void RegisterDirectorMaker(const char* className, DirectorMaker maker) { Makers()[className] = maker; }',
     'cRZCOMDllDirector* GetGZWin32COMDllDirector() { static cGZWin32COMDirector director; return &director; }',
     'cIGZUnknown* DirectorMake(const char* className) {',
     '    const auto it = Makers().find(className);',
     '    return it == Makers().end() ? nullptr : it->second();', '}', '']
report = []
KNOWN = {'nSCRes_cFileParser': '0x5cf9459a'}
ONSTART = {'cGZWinCOMDirector': [0x84174448, 0xc2c2eb0f], 'cGZToolsCOMDirector': [0x414a2b1]}
for d in DIRS:
    path = glob.glob(str(ROOT / f"work/*/{d}.txt"))[0]
    txt = open(path).read()
    parts = re.split(r"^//==== (0x[0-9a-f]+)  ", txt, flags=re.M)
    funcs = {}
    for i in range(1, len(parts), 2):
        title = parts[i + 1].split("\n")[0]
        if "non-virtual" in title: continue
        funcs.setdefault(title, parts[i + 1])
    ctor = next(v for k, v in funcs.items() if k.startswith(f"{d}::{d}()"))
    ctor = re.sub(r"\s+", " ", ctor)
    entries = []
    for m in re.finditer(r"(?:uVar\d = (GZCOM_\w+?)CLSID\(\); )?cRZCOMDllDirector::AddCls\w*\s*\(\s*\(cRZCOMDllDirector \*\)this,\s*(\w+),\s*([\w:]+)\s*\)", ctor):
        gz, idv, creator = m.groups()
        clsid = int(idv, 16) if idv.startswith("0x") else None
        entries.append((clsid, gz, creator, idv))
    creators = {}
    for k, v in funcs.items():
        m = re.match(rf"{d}::(Create\w+)\(\)", k)
        if m:
            cm = re.search(r"(\w+)::\1\(this", v) or re.search(r"(\w+)::Construct\(", v)
            creators[m.group(1)] = cm.group(1) if cm else None
    did = re.search(r"return (0x[0-9a-f]+);", next(v for k, v in funcs.items() if "GetDirectorID" in k)).group(1)
    H.append(f"class {d} : public cRZCOMDllDirector {{\npublic:\n    {d}();\n    std::uint32_t GetDirectorID() const override {{ return {did}; }}")
    if d in ONSTART:
        H.append("    bool OnStart(cIGZCOM* com) override;")
    for name in creators:
        H.append(f"    static cIGZUnknown* {name}();")
    H.append("};\n")
    body = [f"{d}::{d}() {{"]
    if d == 'cGZWinCOMDirector':
        body.append("    AddDirector(GetGZWin32COMDllDirector());")
    for clsid, gz, creator, idv in entries:
        if gz:
            cls = gz[len("GZCOM_"):]
            body.append(f"    AddCls({KNOWN.get(cls, 'gzcom::kCLSID_'+cls)}, +[]() -> cIGZUnknown* {{ return DirectorMake(\"{cls}\"); }});")
            report.append((d, "gzcom", cls))
            continue
        cname = creator.split("::")[-1]
        if "::" in creator:                       # static of another class
            owner = creator.split("::")[0]
            body.append(f"    AddCls({idv}, +[]() -> cIGZUnknown* {{ return DirectorMake(\"{owner}\"); }});")
        elif creator in creators:
            body.append(f"    AddCls({idv}, &{d}::{creator});")
        else:
            body.append(f"    AddCls({idv}, +[]() -> cIGZUnknown* {{ return DirectorMake(\"{creator}\"); }});   // free creator")
    body.append("}")
    C += body + [""]
    if d in ONSTART:
        C.append(f"bool {d}::OnStart(cIGZCOM* com) {{ return StartServices(com, {{{', '.join(hex(x) for x in ONSTART[d])}}}); }}")
    for name, cls in creators.items():
        C.append(f"cIGZUnknown* {d}::{name}() {{ return DirectorMake(\"{cls or name}\"); }}")
    C.append("")
H.append("}  // namespace gz\n")
C.append("}  // namespace gz\n")
(ROOT / "src/rz/COMDirectors.h").write_text("\n".join(H))
(ROOT / "src/rz/COMDirectors.cpp").write_text("\n".join(C))
for r in report: print(r)
