#!/usr/bin/env python3
"""Lists every cSC4PackedRenderState::PackRenderState call site in the game whose 14 arguments are all literals, and writes
scripts/tests/renderstates.inc (one `{...}` initializer per distinct tuple, with the first call site as a comment).
Non-literal sites (computed from properties / materials) are listed on stdout.  Needs the Ghidra MCP backend."""
import bisect, json, pathlib, re, urllib.parse, urllib.request
import sys as _s, pathlib as _p; _s.path.insert(0, str(_p.Path(__file__).resolve().parent)); from ghidra_conn import BASE
root = pathlib.Path(__file__).resolve().parent.parent
def get(url): return json.load(urllib.request.urlopen(BASE + "/" + url, timeout=300))
PACK = "0x100771d00"
refs = [r for r in get(f"get_xrefs_to?address={PACK}&limit=500")["references"] if not r["type"].startswith("DATA")]
syms = sorted((int(l.split(" ", 1)[0], 16), l.rstrip("\n").split(" ", 1)[1]) for l in (root / "notes/symbols-functions-demangled.txt").open())
addrs = [a for a, _ in syms]
funcs = {}
for r in refs:
    fa = int(r["from_address"], 16); i = bisect.bisect_right(addrs, fa) - 1
    funcs[addrs[i]] = syms[i][1]
tuples, dynamic = {}, []
for a, name in sorted(funcs.items()):
    q = urllib.parse.urlencode({"functions": hex(a), "fields": "decompiled_code", "include_call_context": "false"})
    for f in get("get_functions?" + q)["functions"].values():
        text = re.sub(r"\s+", " ", f.get("decompiled_code") or "")
        for m in re.finditer(r"PackRenderState\s*\(([^;]*?)\);", text):
            args = [x.strip() for x in m.group(1).split(",")][1:]
            if len(args) == 14 and all(re.fullmatch(r"true|false|-?\d+|-?\d+\.\d+", x) for x in args):
                tuples.setdefault(tuple(args), name)
            else:
                dynamic.append(name)
lines = ["// Generated by scripts/dump_render_states.py: every literal PackRenderState(...) tuple in the game.",
         "// {colorWrite, depthWrite, depthTest, alphaTest, blend, textureStages, cull, depthFunc, blendSrc, blendDst, alphaFunc, alphaRef, texEnv0, texEnv1}"]
for args, name in sorted(tuples.items()):
    a = list(args)
    a[11] = a[11] if "." in a[11] else a[11] + ".0"
    lines.append("{" + ", ".join(a) + "},  // " + name[:60])
(root / "scripts/tests/renderstates.inc").write_text("\n".join(lines) + "\n")
print(len(tuples), "literal tuples;", len(set(dynamic)), "computed sites:")
for n in sorted(set(dynamic)): print("  ", n[:90])
