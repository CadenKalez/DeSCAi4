#!/usr/bin/env python3
"""Embeds src/render/dx7/DX7Emulator.metal as a C++ raw string (src/render/dx7/DX7EmulatorSource.inc).
Usage: scripts/gen_dx7_shader.py [--check]   (--check exits 1 when the .inc is stale)"""
import sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "src/render/dx7/DX7Emulator.metal").read_text()
out = '// Generated by scripts/gen_dx7_shader.py from DX7Emulator.metal; do not edit.\nstatic const char kDX7EmulatorSource[] = R"MSL(' + src + ')MSL";\n'
dest = root / "src/render/dx7/DX7EmulatorSource.inc"
if "--check" in sys.argv:
    sys.exit(0 if dest.exists() and dest.read_text() == out else 1)
dest.write_text(out)
