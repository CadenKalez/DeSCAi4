#!/usr/bin/env python3
"""Cross-reference our remaining functions with the OpenSC4 clean-room specs.

OpenSC4 (GPL-3, Rust) writes one behaviour spec per subsystem of the Windows build. Their specs and answered questions
describe the same classes we still have to recover, so they are a reading aid next to the Ghidra output: they never
replace transcribing from our binary, and nothing of theirs is copied into src/.

    python3 scripts/opensc4_crossref.py ~/Downloads/OpenSC4-main      # writes notes/opensc4_crossref.md
"""
import collections
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC_DIRS = ("docs/specs", "docs/subsystems", "docs/abi")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    other = pathlib.Path(sys.argv[1]).expanduser()
    docs = {}
    for d in DOC_DIRS:
        for f in sorted((other / d).rglob("*.md")):
            docs[str(f.relative_to(other))] = f.read_text(errors="ignore")

    rows = list(csv.DictReader(open(ROOT / "notes/remaining_functions.csv")))
    per_class = collections.defaultdict(collections.Counter)
    for r in rows:
        per_class[r["class"]][r["status"]] += 1

    lines, covered, total, uncovered = [], 0, 0, []
    for cls, statuses in sorted(per_class.items(), key=lambda kv: -sum(kv[1].values())):
        if cls.startswith("("):
            continue
        n = sum(statuses.values())
        total += n
        pat = re.compile(r"\b" + re.escape(cls) + r"\b")
        hits = sorted(((len(pat.findall(t)), p) for p, t in docs.items() if pat.search(t)), reverse=True)[:4]
        if not hits:
            uncovered.append((cls, n))
            continue
        covered += n
        state = ", ".join(f"{k} {v}" for k, v in statuses.most_common())
        refs = ", ".join(f"`{p}` ({k})" for k, p in hits)
        lines.append(f"| {cls} | {n} | {state} | {refs} |")

    out = [
        "# OpenSC4 specs for our remaining functions",
        "",
        f"Generated by `scripts/opensc4_crossref.py` from `notes/remaining_functions.csv`; do not edit by hand.",
        "",
        "OpenSC4 is a GPL-3 clean-room Rust reimplementation of the Windows build. Its specs describe behaviour, field",
        "meanings and quirks for the same classes; use them next to the Ghidra output when a function is hard to read.",
        "Their addresses are Windows (1.1.641) addresses, not ours. Never copy their code or text into src/: transcribe",
        "from our binary as usual, and a ledger row still needs our own verification.",
        "",
        f"**{covered} of {total}** remaining functions belong to a class their docs mention (number in parentheses =",
        "mentions in that file, a rough measure of depth).",
        "",
        "## Other material worth reading in their repo",
        "",
        "| Path | Use for us |",
        "|---|---|",
        "| `docs/specs/simulator.md` | the clock, speeds, pause and tick order: the reference for wiring the native simulator host |",
        "| `docs/specs/questions/answered/` | resolved RE questions (exact rounding, ordering, edge cases) per subsystem |",
        "| `re/class_id_table.tsv` | 648 message / class / service IDs with names; check against the IDs in our headers |",
        "| `re/tuning/*.json` | simulator tuning exemplars and the demand exemplar graph, dumped from the game data |",
        "| `re/prior_art.md`, `re/prior_art_exemplar_props.md` | community knowledge: exemplar properties, interface IDs, vtable orders |",
        "| `engine/conformance/vectors/*.json` | ~1,250 behaviour cases with expected values; candidates for extra tests of our simulators (needs an op adapter per subsystem) |",
        "| `docs/specs/simulator.md` section 5.8 | the fixed schedule: how to make the game deterministic enough to compare whole cities |",
        "",
        "## Classes with no spec on their side",
        "",
        ", ".join(f"{c} ({n})" for c, n in uncovered) or "none",
        "",
        "## By class",
        "",
        "| Class | Remaining | Status | Their docs |",
        "|---|---:|---|---|",
        *lines,
        "",
    ]
    (ROOT / "notes/opensc4_crossref.md").write_text("\n".join(out))
    print(f"notes/opensc4_crossref.md: {covered} of {total} remaining functions have a spec; {len(uncovered)} classes have none")
    return 0


if __name__ == "__main__":
    sys.exit(main())
