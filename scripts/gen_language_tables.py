#!/usr/bin/env python3
"""Generate src/rz/LanguageTables.inc from the cRZLanguageManager / cRZLanguageUtility exports in work/rz.

The decompile of the name functions is a long run of nested switches (language -> day/month number -> string);
this walks it, resolves the shared-label gotos and the s_* data strings (read from the Mach-O) and writes plain tables.
"""
import re, sys, json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT/"scripts"))
import macho_read
data = macho_read.BIN.read_bytes(); segs = macho_read.segments(data)

def cstr(addr):
    out = b''
    while True:
        b = macho_read.read(addr+len(out), 64, data, segs); i = b.find(b'\0')
        if i >= 0: out += b[:i]; break
        out += b
    return out

def blocks_of(path):
    res = {}
    for b in re.split(r'^//==== ', open(ROOT/path).read(), flags=re.M)[1:]:
        h = b.split('\n', 1)[0]; m = re.match(r'0x\w+\s+(.*)', h)
        if 'thunk' in m.group(1): continue
        res[m.group(1)] = b
    return res
UT = blocks_of('work/rz/cRZLanguageUtility.txt')
MG = blocks_of('work/rz/cRZLanguageManager.txt')
def pick(blocks, prefix): return blocks[[k for k in blocks if k.startswith(prefix)][0]]

def value(tok):
    tok = tok.strip()
    if tok.startswith("'"):
        s = tok[1:-1]
        mp = {'\\a': 7, '\\b': 8, '\\t': 9, '\\n': 10, '\\v': 11, '\\f': 12, '\\r': 13, '\\0': 0}
        if s in mp: return mp[s]
        if s.startswith('\\x'): return int(s[2:], 16)
        return ord(s)
    return int(tok, 0)

def text_of(t):
    if t.startswith('"'): return json.loads(t).encode('latin-1')
    return cstr(int(re.search(r'_([0-9a-f]{9})$', t).group(1), 16))

def nested(block):
    """language -> {number: bytes} for the two-level switches of GetDayName & co."""
    langs = []; table = {}; labels = {}; inner = False; cur = []; label = None
    pend = {}; reset = False; prev = ''
    for ln in block.split('\n'):
        s = ln.strip(); ind = len(ln) - len(ln.lstrip())
        if prev == 'default:': prev = s; continue
        prev = s
        m = re.match(r'^(switchD_\w+):$', s)
        if m:
            if inner and cur: pend[cur[-1]] = m.group(1)
            else: label = m.group(1)
            continue
        if re.match(r'switch\(param_1\) \{', s): inner = True; cur = []; pend.clear(); continue
        if s == '}' and ind == 4 and inner: inner = False; reset = True; continue
        m = re.match(r"case (.+):$", s)
        if m:
            if not inner:
                if reset: langs = []; reset = False
                langs.append(int(m.group(1), 0))
            else:
                v = value(m.group(1))
                if label is not None: pend[v] = label; label = None
                cur.append(v)
            continue
        if inner:
            m = re.match(r'pcVar4 = (.+);', s)
            if m:
                sv = text_of(m.group(1))
                for v in cur:
                    for l in langs: table.setdefault(l, {})[v] = sv
                    if v in pend: labels[pend.pop(v)] = sv
                continue
            m = re.match(r'goto (switchD_\w+);', s)
            if m and 'caseD_15' not in m.group(1) and cur:
                for l in langs: table.setdefault(l, {})[cur[-1]] = ('g', m.group(1))
                cur = []; continue
            if s == 'break;': cur = []
    for l, d in table.items():
        for v, x in list(d.items()):
            if isinstance(x, tuple): d[v] = labels[x[1]]
    return table

def flat(block, var):
    """number -> bytes for a single switch (several case labels may share a string)."""
    res = {}; pend = []
    for ln in block.split('\n'):
        s = ln.strip()
        m = re.match(r"case (.+):$", s)
        if m: pend.append(int(m.group(1), 0)); continue
        if s.startswith('(**') or s.startswith('goto') or s.startswith('default:'): pend = []; continue
        m = re.match(var + r' = (.+);', s)
        if m:
            for v in pend: res[v] = text_of(m.group(1))
            pend = []
    return res

def esc(b):
    out = ''
    for c in b:
        if c == 0x22: out += '\\"'
        elif c == 0x5c: out += '\\\\'
        elif 0x20 <= c < 0x7f and c != 0x3f: out += chr(c)
        else: out += '\\%03o' % c
    return '"' + out + '"'

def u32s(addr, n):
    b = macho_read.read(addr, 4*n, data, segs)
    import struct
    return struct.unpack('<%dI' % n, b)

out = ['// Generated by scripts/gen_language_tables.py from the original name tables; do not edit by hand.']
for fn, cnt, label in (('GetDayName', 7, 'Day'), ('GetAbbrDayName', 7, 'AbbrDay'), ('GetMonthName', 12, 'Month'), ('GetAbbrMonthName', 12, 'AbbrMonth')):
    t = nested(pick(UT, f'cRZLanguageUtility::{fn}('))
    out.append(f'static const NameRow k{label}Rows[] = {{')
    for l in sorted(t):
        names = ', '.join(esc(t[l][i]) if i in t[l] else 'nullptr' for i in range(1, cnt+1))
        out.append(f'    {{{l}, {{{names}}}}},')
    out.append('};')
def table(name, mapping, size, default='nullptr'):
    out.append(f'static const char* const {name}[{size}] = {{')
    for i in range(size):
        out.append(f'    {esc(mapping[i]) if i in mapping else default},   // {i}')
    out.append('};')
en = flat(pick(MG, 'cRZLanguageManager::GetLanguageEnglishName('), 'pcVar1')
table('kLanguageEnglishNames', en, 0x2d)
dr = flat(pick(MG, 'cRZLanguageManager::GetLanguageDirectoryName('), 'pcVar3')
dr[2] = b'UKEnglsh'   # the default arm tests `lang != 2` by hand
table('kLanguageDirectoryOverrides', dr, 0x2d)
iso = flat(pick(MG, 'cRZLanguageManager::GetISO639LanguageCodeFromLanguageID('), 'pcVar1')
table('kISO639Codes', iso, 0x2d)
cc = flat(pick(MG, 'cRZLanguageManager::GetISO3166CountryCodeFromCountryID('), 'pcVar1')
table('kISO3166Codes', cc, 0x39)
cn = flat(pick(MG, 'cRZLanguageManager::GetCountryEnglishName('), 'pcVar1')
table('kCountryEnglishNames', cn, 0x39)
p = u32s(0x100a15eb0, 0x37); d = u32s(0x100a15f90, 0x2b)
out.append('static const std::uint32_t kPrimaryLanguageForCountry[0x37] = {' + ', '.join(map(str, p)) + '};   // country 2 + i')
out.append('static const std::uint32_t kDefaultCountryForLanguage[0x2b] = {' + ', '.join(map(str, d)) + '};   // language 2 + i')
(ROOT/'src/rz/LanguageTables.inc').write_text('\n'.join(out) + '\n')
print('ok', len(out))
