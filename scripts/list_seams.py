#!/usr/bin/env python3
"""Generate docs/SEAMS.md: every host/seam interface in src/ (I*Host, I*Services, I*Api and the terrain view's ITerrain*),
where it is declared, which classes use it and whether anything implements it outside tests.
usage: python3 scripts/list_seams.py   (rewrites the generated section; the hand-written hookup guide above it is kept)"""
import pathlib, re, collections
ROOT = pathlib.Path(__file__).resolve().parent.parent
decl = re.compile(r"^(?:class|struct) (I[A-Z][A-Za-z0-9]*(?:Host|Services?|Api)|ITerrain[A-Za-z]+)\b(?!\s*;)", re.M)
seams = {}
for p in sorted((ROOT/"src").rglob("*.h")):
    t = p.read_text(errors="replace")
    for m in decl.finditer(t):
        seams.setdefault(m.group(1), p.relative_to(ROOT).as_posix())
src_files = [p for p in (ROOT/"src").rglob("*") if p.suffix in (".h", ".cpp", ".mm")]
test_files = list((ROOT/"scripts").rglob("*.cpp")) + list((ROOT/"scripts").rglob("*.mm")) + list((ROOT/"scripts").rglob("*.h"))
texts = {p: p.read_text(errors="replace") for p in src_files + test_files}
rows = []
for name, header in sorted(seams.items()):
    users, impl_src, impl_test = set(), set(), set()
    inherit = re.compile(r"(?:class|struct)\s+\w+[^{;]*:\s*[^{;]*\b(?:public\s+)?" + name + r"\b")
    for p, t in texts.items():
        rel = p.relative_to(ROOT).as_posix()
        if name not in t or rel == header: continue
        if inherit.search(t):
            (impl_test if p in test_files else impl_src).add(rel)
        elif p in src_files:
            users.add(rel)
    status = "implemented" if impl_src else ("test fake only" if impl_test else "NOT IMPLEMENTED")
    rows.append((name, header, ", ".join(sorted(users)[:3]) + (" ..." if len(users) > 3 else ""), status, ", ".join(sorted(impl_src | impl_test)[:2])))
gen = ["<!-- generated:start -->", "## Seam registry (generated by scripts/list_seams.py)", "",
       f"{len(rows)} seams, {sum(r[3]=='NOT IMPLEMENTED' for r in rows)} with no implementation at all, "
       f"{sum(r[3]=='test fake only' for r in rows)} with only a test fake.", "",
       "| Seam | Declared in | Used by | Status | Implemented by |", "|---|---|---|---|---|"]
for r in rows: gen.append(f"| `{r[0]}` | `{r[1]}` | {r[2]} | {r[3]} | {r[4]} |")
gen.append("<!-- generated:end -->")
out = ROOT/"docs/SEAMS.md"
text = out.read_text() if out.exists() else "# Seams\n\n"
block = "\n".join(gen)
if "<!-- generated:start -->" in text:
    text = re.sub(r"<!-- generated:start -->.*?<!-- generated:end -->", lambda m: block, text, flags=re.S)
else:
    text = text.rstrip() + "\n\n" + block + "\n"
out.write_text(text)
print(len(rows), "seams")
