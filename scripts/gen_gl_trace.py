#!/usr/bin/env python3
"""Generates scripts/tests/gl_trace.h: a TraceGL implementation of sgl::IGLApi that records every call as text
("Enable(3553)"), for the render-layer tests. Pointer arguments are logged as 'p' (or 'null')."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "src/render/GLApi.h").read_text()
body = src[src.index("class IGLApi"):src.index("// The process-wide GL")]
methods = re.findall(r"virtual\s+([\w:\*<> ]+?)\s+(\w+)\(([^)]*)\)\s*=\s*0;", body, re.S)
out = ["// Generated by scripts/gen_gl_trace.py — do not edit.",
       "#pragma once", "#include <type_traits>", "#include <cstdio>", "#include <string>", "#include <vector>", '#include "render/GLApi.h"', "",
       "namespace sgl {", "class TraceGL : public IGLApi {", "public:",
       "    std::vector<std::string> log;", "    void clear() { log.clear(); }",
       "    std::string joined() const { std::string s; for (auto& l : log) { s += l; s += ';'; } return s; }",
       "    bool has(const std::string& call) const { for (auto& l : log) if (l == call) return true; return false; }",
       "    int count(const std::string& prefix) const { int n = 0; for (auto& l : log) if (l.compare(0, prefix.size(), prefix) == 0) ++n; return n; }",
       "    // behaviour hooks",
       "    GLuint nextId = 100; std::string extensions; std::vector<unsigned char> mapped = std::vector<unsigned char>(1 << 16);",
       "    GLint integers[4] = {0, 0, 640, 480}; bool enabled[0x10000] = {};",
       "    std::function<void(GLint, GLint, GLsizei, GLsizei, GLenum, GLenum, void*)> onReadPixels;",
       "private:",
       "    template <class T> static std::string T_(const T& v) {",
       "        if constexpr (std::is_pointer_v<T>) return v ? \"p\" : \"null\";",
       "        else if constexpr (std::is_floating_point_v<T>) { char b[64]; snprintf(b, sizeof b, \"%g\", static_cast<double>(v)); return b; }",
       "        else return std::to_string(static_cast<long long>(v));",
       "    }",
       "public:"]
special = {
    "IsEnabled": "return enabled[cap & 0xffff];",
    "GetIntegerv": "if (pname == 0xba2) for (int i = 0; i < 4; ++i) out[i] = integers[i]; else out[0] = 0;",
    "GetBooleanv": "out[0] = out[1] = out[2] = out[3] = 1;",
    "GetString": "return name == 0x1f03 ? extensions.c_str() : \"\";",
    "GenTextures": "for (GLsizei i = 0; i < n; ++i) ids[i] = nextId++;",
    "GenBuffers": "for (GLsizei i = 0; i < n; ++i) ids[i] = nextId++;",
    "GenVertexArraysAPPLE": "for (GLsizei i = 0; i < n; ++i) ids[i] = nextId++;",
    "GenProgramsARB": "for (GLsizei i = 0; i < n; ++i) ids[i] = nextId++;",
    "MapBuffer": "return mapped.data();",
    "ReadPixels": "if (onReadPixels) onReadPixels(x, y, w, h, format, type, data);",
    "Enable": "enabled[cap & 0xffff] = true;",
    "Disable": "enabled[cap & 0xffff] = false;",
}
for ret, name, params in methods:
    plist = [p.strip() for p in params.split(",") if p.strip()]
    names = []
    for p in plist:
        names.append(re.findall(r"(\w+)\s*$", p)[0])
    logexpr = " + \",\" + ".join(f"T_({n})" for n in names) if names else 'std::string()'
    sig = ", ".join(plist)
    body_ = special.get(name, "")
    retstmt = ""
    if ret.strip() == "bool" and name not in special: retstmt = "return false;"
    out.append(f"    {ret} {name}({sig}) override {{ log.push_back(std::string(\"{name}(\") + {logexpr} + \")\"); {body_} {retstmt} }}")
out += ["};", "}  // namespace sgl", ""]
(root / "scripts/tests/gl_trace.h").write_text("\n".join(out).replace('#include <string>', '#include <functional>\n#include <string>'))
print("wrote", len(methods), "methods")
