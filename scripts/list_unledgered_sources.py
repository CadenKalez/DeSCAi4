#!/usr/bin/env python3
"""List the source files the ledger does not cite, and say why. Writes notes/port_only_sources.md.

A file is cited when some ledger row's `source` column names it (directly or through its header). Files that
are never cited are either port-side scaffolding (no symbols in the binary), generated, or a tool — this
report makes that distinction explicit so "no ledger row" is never mistaken for "work we forgot to record".

usage: scripts/list_unledgered_sources.py
"""
import collections, csv, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "notes/port_only_sources.md"
GENERATED = ("GZCOMCreators",)
TOOL_DIRS = ("src/tools/", "src/app/", "src/dbpf/", "src/game/")


def owners(text):
    return set(re.findall(r"\b([cn][A-Z][A-Za-z0-9_]*)::", text))


def main():
    symbols = set()
    for line in (ROOT / "notes/symbols-functions-demangled.txt").read_text(errors="replace").splitlines():
        _, _, name = line.partition(" ")
        symbols.update(owners(name))

    ledger = list(csv.DictReader((ROOT / "notes/ledger.csv").open()))
    cited = set()
    ledgered = collections.defaultdict(set)      # class -> the files its rows cite
    for r in ledger:
        own = owners(r["symbol"])
        for tok in re.split(r"[|+,\s]+", r["source"]):
            if tok.endswith((".cpp", ".h")):
                cited.add(tok)
                for o in own:
                    ledgered[o].add(tok)

    rows = []
    for p in sorted((ROOT / "src").rglob("*.cpp")):
        rel = str(p.relative_to(ROOT))
        if rel in cited or str(p.with_suffix(".h").relative_to(ROOT)) in cited:
            continue
        text = p.read_text(errors="replace")
        own = owners(text)
        in_binary = sorted(o for o in own if o in symbols)
        if rel.startswith(TOOL_DIRS):
            why = "port tooling (never part of the original binary)"
        elif any(g in p.name for g in GENERATED):
            why = "generated by scripts/gen_directors.py"
        elif not own:
            why = "port glue: free functions / adapters, no class of its own"
        elif not in_binary:
            why = "port-side class(es) with no symbols in the binary: " + ", ".join(sorted(own)[:4])
        elif all(o in ledgered for o in in_binary):
            where = sorted({f for o in in_binary for f in ledgered[o]})[:2]
            why = "cited from another file (" + ", ".join(f"`{w}`" for w in where) + ")"
        else:
            missing = [o for o in in_binary if o not in ledgered]
            why = "**check**: class(es) in the binary with no ledger row at all: " + ", ".join(missing[:4])
        rows.append((rel, why))

    lines = ["# Source files the ledger does not cite", "",
             "Generated by `scripts/list_unledgered_sources.py`. Every `.cpp` under `src/` that no ledger row",
             "names — directly or through its header — with the reason. Port-side files are expected here; a",
             "`**check**` line means the binary has those classes but the ledger has no provenance for this file.", "",
             f"Files listed: **{len(rows)}**", "",
             "| File | Why it is not cited |", "|---|---|"]
    for rel, why in rows:
        lines.append(f"| `{rel}` | {why} |")
    OUT.write_text("\n".join(lines) + "\n")
    flagged = sum(1 for _, w in rows if w.startswith("**check**"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} files, {flagged} flagged for review")


main()
