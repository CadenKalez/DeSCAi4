#!/usr/bin/env python3
"""gen_stub_iface.py OUT.cpp HEADER.h Derived Base1,Base2 ... : writes a neutral implementation of Derived (merging the pure
virtuals of the listed bases) with a factory `Derived* NewStub<Derived>()`. Used for hosts passed to constructors."""
import re, sys, glob
out, header, derived = sys.argv[1], sys.argv[2], sys.argv[3]
bases = sys.argv[4].split(',') if len(sys.argv) > 4 else []
def strip(t):
    t = re.sub(r'//[^\n]*', '', t); return re.sub(r'/\*.*?\*/', '', t, flags=re.S)
heads = {p: strip(open(p).read()) for p in glob.glob('src/sc4/*.h')}
def body(name):
    for q, u in heads.items():
        b = re.search(r'(?:class|struct)\s+' + name + r'\s*(?::\s*public\s+[\w:]+\s*)?\{', u)
        if b:
            i = b.end(); d = 1
            while d and i < len(u):
                d += (u[i] == '{') - (u[i] == '}'); i += 1
            return u[b.end():i-1]
    raise SystemExit('no ' + name)
seen = set(); sig = []
for name in [derived] + bases:
    for pm in re.finditer(r'virtual\s+([^;{}()]+?)\s*\b(\w+)\s*\(([^;{}]*?)\)\s*(const)?\s*=\s*0\s*;', body(name), re.S):
        ret, mn, args, cst = pm.group(1).strip(), pm.group(2), ' '.join(pm.group(3).split()), pm.group(4) or ''
        if mn.startswith('~') or (mn, args) in seen: continue
        seen.add((mn, args))
        args2 = re.sub(r'\s*=\s*[^,)]+', '', args)
        if ret == 'void': ctx = '{}'
        elif ret.endswith('&'): ctx = '{ static %s dummy{}; return dummy; }' % ret[:-1].replace('const', '').strip()
        else: ctx = '{ return {}; }'
        sig.append('    %s %s(%s)%s override %s' % (ret, mn, args2, ' const' if cst else '', ctx))
open(out, 'w').write('// Generated by scripts/gen_stub_iface.py: a neutral %s for classes built with a host argument.\n#include <string>\n#include <vector>\n#include "sc4/%s"\n#include "sc4/DBSegment.h"\n\nnamespace sc4 {\nnamespace {\nstruct Stub%s final : %s {\n%s\n};\n}  // namespace\n\n%s* NewStub%s() { static Stub%s s; return &s; }\n\n}  // namespace sc4\n' % (derived, header, derived, derived, '\n'.join(sig), derived, derived, derived))
