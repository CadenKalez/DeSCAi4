#!/usr/bin/env python3
"""How was each recovered function verified, and which ones deserve a disassembly re-check?

    python3 scripts/audit_exactness.py        # writes notes/exactness_audit.md

Evidence kinds come from the ledger's evidence column. A recovered function is listed for re-check when its Ghidra export
(work/*/*.txt) shows decompiler artifacts that usually hide real behaviour (register arguments that were lost, SSE
instructions Ghidra could not express, unrecovered jump tables) and its evidence names neither a disassembly check nor
an oracle. The marker list over-reports (a lost argument in a one-line getter is harmless): it is a worklist, not a verdict.
"""
import collections
import csv
import glob
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
MARKS = re.compile(r"extraout_XMM|in_XMM|pmovzx|pextr|punpck|unaff_|in_R[CD]X|in_stack|Could not recover jumptable|halt_baddata|Bad instruction")
HEADER = re.compile(r"^//==== 0x([0-9a-f]+)\s+(.*)$")


def kind(evidence: str) -> str:
    e = evidence.lower()
    if "oracle" in e:
        return "oracle (decompiled code run against the port on random inputs)"
    if "disassembl" in e or "otool" in e:
        return "checked against the disassembly"
    if "real-data" in e or "real data" in e or "retail" in e or "game data" in e:
        return "real game data"
    if "test" in e:
        return "unit test only"
    return "no test named"


def main() -> None:
    ledger = {int(r["address"], 16): r for r in csv.DictReader(open(ROOT / "notes/ledger.csv"))}
    kinds = collections.Counter(kind(r["evidence"]) for r in ledger.values() if r["status"] == "recovered")
    partial = sum(1 for r in ledger.values() if r["status"] == "recovered-partial")
    total = sum(kinds.values())

    flagged = collections.defaultdict(list)
    for path in sorted(glob.glob(str(ROOT / "work/*/*.txt"))):
        current, body = None, []

        def finish():
            if current is None or not MARKS.search("".join(body)):
                return
            row = ledger.get(current)
            if row and row["status"] == "recovered" and kind(row["evidence"]) in ("unit test only", "no test named"):
                flagged[row["source"].split("|")[0]].append((current, row["symbol"]))

        for line in open(path, errors="replace"):
            m = HEADER.match(line)
            if m:
                finish()
                current, body = int(m.group(1), 16), []
            else:
                body.append(line)
        finish()

    out = ["# Exactness audit", "", "Generated by `scripts/audit_exactness.py`; do not edit by hand.", "",
           "The port is a transcription checked by tests; none of this proves the machine code behaves identically. How the",
           f"{total:,} `recovered` rows were verified (plus {partial:,} `recovered-partial`):", "",
           "| Evidence | Rows | Share |", "|---|---:|---:|"]
    out += [f"| {k} | {v:,} | {100 * v / total:.1f}% |" for k, v in kinds.most_common()]
    count = sum(len(v) for v in flagged.values())
    out += ["", f"## Worklist: {count:,} functions with decompiler artifacts and only a unit test", "",
            "| Source | Functions |", "|---|---:|"]
    out += [f"| `{s}` | {len(v)} |" for s, v in sorted(flagged.items(), key=lambda kv: -len(kv[1]))]
    (ROOT / "notes/exactness_audit.md").write_text("\n".join(out) + "\n")
    print(f"notes/exactness_audit.md: {count} functions to re-check, {len(flagged)} files")


if __name__ == "__main__":
    main()
