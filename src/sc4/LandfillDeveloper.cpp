// @ 0x1000614e4. Take the pollution simulator's garbage supply, clamp it, scale it by the funded fraction
// of the maintenance cost, hand it to every zone and publish the remaining capacity.
void cSC4LandfillDeveloper::DoMonthlySimulation() {
    if (zones_.empty()) {
        RecordHistoryData(kLandfillHistoryCapacity, capacity_);
        int uncollected = pollution_ ? pollution_->GetTotalGarbageUncollected() : 0;
        if (uncollected < 0) uncollected = 0;
        int supply = pollution_ ? pollution_->GetGarbageSupply() : 0;
        if (supply < 0) supply = 0;
        RecordHistoryData(kLandfillHistoryGarbage, static_cast<std::uint32_t>(supply + uncollected + static_cast<int>(garbage_)));
        UpdateBudgetRequirements();
        if (pollution_) pollution_->SetGarbageCapacity(0);   // the original tail-calls this
        return;
    }

    const std::int64_t budget = GetCurrentBudget();          // this->vslot 0x40
    std::uint32_t take = pollution_ ? static_cast<std::uint32_t>(pollution_->GetGarbageSupply()) : 0u;
    if (static_cast<std::int32_t>(take) < 0) take = 0;
    if (take > g_tunables.maxGarbageToTakePerMonth) take = g_tunables.maxGarbageToTakePerMonth;
    int garbageAvailable = static_cast<int>(take);
    if (0 < maintenanceCost_ && budget < maintenanceCost_) {
        garbageAvailable = static_cast<int>(static_cast<float>(garbageAvailable) *
                                            (static_cast<float>(budget) / static_cast<float>(maintenanceCost_)));
    }

    int available = 0;
    for (cSC4LandfillZone* zone : zones_) {
        zone->UpdateZone(garbageAvailable);
        if (zone->Connected()) available += zone->GetAvailableCapacity();
    }
    if (pollution_) pollution_->SetGarbageCapacity(available);
    UpdateBudgetRequirements();
    UpdateCapacityValues();
    RecordHistoryData(kLandfillHistoryCapacity, capacity_);

    int uncollected = pollution_ ? pollution_->GetTotalGarbageUncollected() : 0;
    if (uncollected < 0) uncollected = 0;
    const int stored = static_cast<int>(garbage_);
    int supply = pollution_ ? pollution_->GetGarbageSupply() : 0;
    if (supply < 0) supply = 0;
    RecordHistoryData(kLandfillHistoryGarbage, static_cast<std::uint32_t>(supply + stored + uncollected));
}

// @ 0x10006197a: the sum of every zone's maintenance cost (saturating on a negative cost) goes into the
// garbage department's line item 30, and is kept for the monthly budget scaling.
void cSC4LandfillDeveloper::UpdateBudgetRequirements() {
    std::int64_t total = 0;
    for (cSC4LandfillZone* zone : zones_) {
        const std::int64_t cost = zone->GetMaintenanceCost();
        if (cost < 0) {
            total = 0x7fffffffffffffffLL;
        } else {
            total += cost;
        }
    }
    ILandfillBudgetLine* line = department_ ? department_->GetLineItem(kLandfillBudgetLine) : nullptr;
    if (line) {
        line->AddRef();
        line->SetFullExpenses(total);
        line->Release();
    }
    // Quirk kept from the original: the line item is not checked for null. Deviation: this port skips the
    // call instead of dereferencing it.
    maintenanceCost_ = total;
}

// @ 0x100062012: the department's line item 30 current expenses (a tail call in the original).
std::int64_t cSC4LandfillDeveloper::GetCurrentBudget() {
    if (!department_) return 0;
    ILandfillBudgetLine* line = department_->GetLineItem(kLandfillBudgetLine);
    if (!line) return 0;
    return line->GetCurrentExpenses();
}

// @ 0x10006221a: the funded fraction of the maintenance cost; 1.0 when there is no maintenance cost.
float cSC4LandfillDeveloper::GetEfficiency() {
    const std::int64_t budget = GetCurrentBudget();          // this->vslot 0x40
    if (maintenanceCost_ < 1) return 1.0f;
    return static_cast<float>(budget) / static_cast<float>(maintenanceCost_);
}

// @ 0x100062032: a cRZMessage2Standard(0x89efa536, data1 = id, data2 = value) sent on the message server.
void cSC4LandfillDeveloper::RecordHistoryData(std::uint32_t id, std::uint32_t value) {
    if (!messageServer_) return;
    auto* message = new cRZMessage2Standard();
    message->AddRef();
    message->SetType(kLandfillHistoryMessageType);
    message->SetData1(id);
    message->SetData2(value);
    messageServer_->MessageSend(message);
    message->Release();
}

