// @ 0x1000609ec: sum the capacity and the stored garbage of the connected zones, saturating at 0xffffffff.
void cSC4LandfillDeveloper::UpdateCapacityValues() {
    capacity_ = 0;
    garbage_ = 0;
    for (cSC4LandfillZone* zone : zones_) {
        if (!zone->Connected()) continue;
        int available = 0, zoneGarbage = 0, zoneCapacity = 0;
        zone->GetCapacity(available, zoneGarbage, zoneCapacity);
        const std::uint32_t garbage = static_cast<std::uint32_t>(zoneGarbage);
        const std::uint32_t sumGarbage = garbage + garbage_;
        garbage_ = sumGarbage < garbage ? 0xffffffffu : sumGarbage;         // CARRY4 clamp
        const std::uint32_t capacity = static_cast<std::uint32_t>(zoneCapacity);
        const std::uint32_t sumCapacity = capacity + capacity_;
        capacity_ = sumCapacity < capacity ? 0xffffffffu : sumCapacity;     // CARRY4 clamp
    }
}

// @ 0x1000616a2: a zoning change. Zone type 0xe merges the region into the first overlapping zone (or
// creates one when nothing overlaps); every other type just dezones the overlapping cells.
void cSC4LandfillDeveloper::DoZoneChange(const LandfillCellRegion* region, std::uint32_t zoneType) {
    if (!region) return;
    const LandfillRect bounds = region->bounds;
    // The overlap test window is inflated by one cell on every side (PADDD with {-1, -1, 1, 1}).
    const LandfillRect inflated{bounds.x0 - 1, bounds.z0 - 1, bounds.x1 + 1, bounds.z1 + 1};
    std::list<cSC4LandfillZone*> overlapping;
    for (cSC4LandfillZone* zone : zones_) {
        const LandfillRect& zoneRect = zone->Region()->bounds;
        if (inflated.x1 < zoneRect.x0 || inflated.x0 > zoneRect.x1) continue;
        if (inflated.z0 > zoneRect.z1 || inflated.z1 < zoneRect.z0) continue;
        overlapping.push_back(zone);
    }
    const bool hadOverlap = !overlapping.empty();

    if (hadOverlap) {
        bool first = true;
        for (cSC4LandfillZone* zone : overlapping) {
            if (zoneType == kLandfillZoneTypeLandfill) {
                zone->ShutdownZoneEffects();
                if (first) {
                    zone->AddRegionToZone(*region);
                    zone->PopulateZone();
                    zone->RecalculateCapacity();
                    zone->InitZoneEffects();
                } else {
                    HandleZoneOverlap(zone, *region, false, false);
                }
            } else {
                HandleZoneOverlap(zone, *region, false, true);
            }
            first = false;
        }
        overlapping.clear();
        UpdateBudgetRequirements();
    }

    if (zoneType == kLandfillZoneTypeLandfill && !hadOverlap) {
        auto* zone = new cSC4LandfillZone(ZoneHostOrNull(), *region);
        zone->AddRef();
        zone->Init();
        float average = 0.0f, maximum = 0.0f, minimum = 0.0f;
        const float variance = GetAltitudeVariance(bounds, average, maximum, minimum);
        if (variance <= g_tunables.levelToleranceThreshold) {
            zone->SetLevelHeight(average);                      // +0x50
        } else {
            zone->LevelRect(bounds, average, false);            // useTerrain = false
        }
        zone->PopulateZone();
        zone->RecalculateCapacity();
        zones_.push_front(zone);                                // the original links before begin()
    }
    UpdateCapacityValues();
}

// @ 0x100061a2c: every zone handles the terrain change; the ones that end up with no cell left are removed
// (and fully dezoned) afterwards.
void cSC4LandfillDeveloper::DoTerrainChanged(const LandfillRect& rect) {
    std::list<cSC4LandfillZone*> dezoned;
    for (cSC4LandfillZone* zone : zones_) {
        zone->HandleTerrainChange(rect);
        if (zone->IsCompletelyDezoned()) dezoned.push_back(zone);
    }
    for (cSC4LandfillZone* zone : dezoned) RemoveZone(zone, true);
    dezoned.clear();
}

// @ 0x100061b22: unlink the first matching node, optionally dezone every remaining cell, then destroy the
// zone (Shutdown + Release, which destroys below a count of 2).
void cSC4LandfillDeveloper::RemoveZone(cSC4LandfillZone* zone, bool dezoneCells) {
    if (!zone) return;
    for (auto it = zones_.begin(); it != zones_.end(); ++it) {
        if (*it == zone) {
            zones_.erase(it);
            break;
        }
    }
    if (dezoneCells) {
        const LandfillCellRegion* region = zone->Region();
        if (region) {
            const LandfillRect b = region->bounds;
            for (int x = b.x0; x <= b.x1; ++x) {
                for (int z = b.z0; z <= b.z1; ++z) {
                    if (region->Test(x, z)) zone->DezoneCell(x, z, true, true);
                }
            }
        }
    }
    zone->Shutdown();
    zone->Release();
}

// @ 0x100061c12: dezone the intersection of a zone and the changed region, then either drop the zone or
// refresh its capacity and the terrain rectangle.
void cSC4LandfillDeveloper::HandleZoneOverlap(cSC4LandfillZone* zone, const LandfillCellRegion& region,
                                              bool updateZoneManager, bool removeTile) {
    if (!zone) return;
    const LandfillRect& zoneRect = zone->Region()->bounds;
    const LandfillRect& regionRect = region.bounds;
    // SC4Rect<int>::IntersectRect @ 0x100314ce8 (inclusive; touching rectangles do overlap).
    LandfillRect intersect;
    intersect.x0 = zoneRect.x0 < regionRect.x0 ? regionRect.x0 : zoneRect.x0;
    intersect.z0 = zoneRect.z0 < regionRect.z0 ? regionRect.z0 : zoneRect.z0;
    intersect.x1 = zoneRect.x1 < regionRect.x1 ? zoneRect.x1 : regionRect.x1;
    intersect.z1 = zoneRect.z1 < regionRect.z1 ? zoneRect.z1 : regionRect.z1;
    if (intersect.x0 > intersect.x1 || intersect.z0 > intersect.z1) return;

    DezoneArea(*zone, intersect, region, updateZoneManager, removeTile);
    if (zone->IsCompletelyDezoned()) {
        RemoveZone(zone, true);
    } else {
        zone->RecalculateCapacity();
    }
    if (terrain_) terrain_->RefreshRect(intersect);   // terrain->0x228(terrain, 1, 1, &rect, 5)
}

// @ 0x100062120: dezone every cell of `rect` that is set in `region`'s map, then mark the zone dezoned when
// it has no valid garbage heap left.
void cSC4LandfillDeveloper::DezoneArea(cSC4LandfillZone& zone, const LandfillRect& rect,
                                       const LandfillCellRegion& region, bool updateZoneManager,
                                       bool removeTile) {
    for (int x = rect.x0; x <= rect.x1; ++x) {
        for (int z = rect.z0; z <= rect.z1; ++z) {
            if (region.Test(x, z)) zone.DezoneCell(x, z, updateZoneManager, removeTile);
        }
    }
    if (zone.GetNumValidHeaps() < 1) zone.SetKnownDezoned(true);   // +0x40
}

// @ 0x100061cb8: centre altitude, then the mean / minimum / maximum of every cell in the rect with the
// "below sea level + 1" clamp. Returns |maximum - minimum|.
float cSC4LandfillDeveloper::GetAltitudeVariance(const LandfillRect& rect, float& average, float& maximum,
                                                 float& minimum) {
    float wx = 0.0f, wz = 0.0f;
    if (city_) city_->CellToWorld((rect.x0 + rect.x1) / 2, (rect.z0 + rect.z1) / 2, wx, wz);
    const float centerAltitude = terrain_ ? terrain_->GetAltitude(wx, wz) : 0.0f;
    minimum = centerAltitude;
    maximum = centerAltitude;
    const float seaLevel = terrain_ ? terrain_->GetSeaLevel() : 0.0f;

    float sum = 0.0f, count = 0.0f;
    for (int x = rect.x0; x <= rect.x1; ++x) {
        for (int z = rect.z0; z <= rect.z1; ++z) {
            if (city_) city_->CellToWorld(x, z, wx, wz);
            float altitude = terrain_ ? terrain_->GetAltitude(wx, wz) : 0.0f;
            if (altitude < seaLevel) altitude = seaLevel + 1.0f;
            if (minimum > altitude) {
                minimum = altitude;
            } else if (maximum < altitude) {
                maximum = altitude;
            }
            sum += altitude;
            count += 1.0f;
        }
    }
    average = 0.0f < count ? sum / count : 0.0f;
    return std::fabs(maximum - minimum);
}

// @ 0x100061e70: the cost of levelling the region to an existing zone's height (or to the region's mean
// altitude when nothing overlaps), plus the terrain cost when the variance is too large.
std::int32_t cSC4LandfillDeveloper::GetZoningCost(const LandfillCellRegion* region) {
    if (!region) return 0;
    const LandfillRect bounds = region->bounds;
    float level = 0.0f;
    bool haveLevel = false;
    for (cSC4LandfillZone* zone : zones_) {
        const LandfillRect& zoneRect = zone->Region()->bounds;
        // GetZoningCost tests the *inclusive* intersection (unlike GetLandfillZoneFromCell).
        if (zoneRect.x0 <= bounds.x1 && bounds.x0 <= zoneRect.x1 && zoneRect.z0 <= bounds.z1 &&
            bounds.z0 <= zoneRect.z1) {
            level = zone->LevelHeight();                       // +0x50
            haveLevel = true;
            break;
        }
    }
    if (!haveLevel) {
        float average = 0.0f, maximum = 0.0f, minimum = 0.0f;
        const float variance = GetAltitudeVariance(bounds, average, maximum, minimum);
        if (variance <= g_tunables.levelToleranceThreshold) return 0;
        level = average;
    }

    float sum = 0.0f;
    for (int x = bounds.x0; x <= bounds.x1; ++x) {
        for (int z = bounds.z0; z <= bounds.z1; ++z) {
            if (!region->Test(x, z)) continue;
            float wx = 0.0f, wz = 0.0f;
            if (city_) city_->CellToWorld(x, z, wx, wz);
            const float altitude = terrain_ ? terrain_->GetAltitude(wx, wz) : 0.0f;
            sum += std::fabs(level - altitude);
        }
    }
    return RoundFloatToEvenInt(sum * g_tunables.costPerCellHeightChange);
}

// @ 0x1000621d8: the zone whose rectangle contains the cell. Quirk kept: the upper bounds are exclusive.
cSC4LandfillZone* cSC4LandfillDeveloper::GetLandfillZoneFromCell(int x, int z) {
    for (cSC4LandfillZone* zone : zones_) {
        const LandfillRect& b = zone->Region()->bounds;
        if (b.x0 <= x && b.z0 <= z && x < b.x1 && z < b.z1) return zone;
    }
    return nullptr;
}

