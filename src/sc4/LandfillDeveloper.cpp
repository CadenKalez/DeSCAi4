// @ 0x100060c6c: the simulator agent, the five services (only when the slot is still null), the five
// notifications, and the tuning exemplar the first time.
bool cSC4LandfillDeveloper::Init() {
    if (initialised_) return true;
    initialised_ = true;
    if (!tunablesRead_) {
        ReadTuningParams();
        tunablesRead_ = true;
    }
    if (!g_host) return true;

    // cRZString("cSC4LandfillDeveloper"), interval 6, flags 2.
    g_host->AddSimulatorAgent(static_cast<cIGZMessageTarget2*>(this), kLandfillAgentInterval,
                              kLandfillAgentName, kLandfillAgentFlags);
    if (!city_) {
        city_ = g_host->City();
        if (city_) city_->AddRef();
    }
    if (!terrain_) {
        terrain_ = g_host->Terrain();
        if (terrain_) terrain_->AddRef();
    }
    if (!pollution_) {
        pollution_ = g_host->Pollution();
        if (pollution_) pollution_->AddRef();
    }
    if (!budget_) {
        budget_ = g_host->Budget();
        if (budget_) budget_->AddRef();
    }
    if (!messageServer_) {
        messageServer_ = g_host->MessageServer();
        if (messageServer_) {
            messageServer_->AddRef();
            for (std::uint32_t type : kLandfillNotifications) {
                messageServer_->AddNotification(static_cast<cIGZMessageTarget2*>(this), type);
            }
        }
    }
    return true;
}

// @ 0x100060f4c: the notifications and the message server, every zone (Shutdown + Release) and the list,
// the department then the four other services, and finally the simulator agent (through the global city).
bool cSC4LandfillDeveloper::Shutdown() {
    if (!initialised_) return true;
    initialised_ = false;
    if (messageServer_) {
        for (std::uint32_t type : kLandfillNotifications) {
            messageServer_->RemoveNotification(static_cast<cIGZMessageTarget2*>(this), type);
        }
        messageServer_->Release();
        messageServer_ = nullptr;
    }
    while (!zones_.empty()) {
        cSC4LandfillZone* zone = zones_.front();
        zone->Shutdown();
        zone->Release();
        zones_.pop_front();
    }
    if (department_) {
        department_->Release();
        department_ = nullptr;
    }
    if (budget_) {
        budget_->Release();
        budget_ = nullptr;
    }
    if (pollution_) {
        pollution_->Release();
        pollution_ = nullptr;
    }
    if (terrain_) {
        terrain_->Release();
        terrain_ = nullptr;
    }
    if (city_) {
        city_->Release();
        city_ = nullptr;
    }
    // The original reads SL::spCity again here (vslot 0x190 -> simulator vslot 0xa8 RemoveAgent) after it
    // has just released the stored city pointer.
    if (g_host) g_host->RemoveSimulatorAgent(static_cast<cIGZMessageTarget2*>(this));
    return true;
}

// @ 0x100060e34: the class statics come from the exemplar {0x6534284a, 0x67cd5fa1, 0x6a2806af} (iid
// 0xa52160f5) through eight cSCPropertyHelp reads. A missing exemplar leaves every static untouched.
void cSC4LandfillDeveloper::ReadTuningParams() {
    if (!g_host) return;
    cISCPropertyHolder* holder = g_host->TuningExemplar();
    if (!holder) return;
    LandfillTunables& t = LandfillDeveloperTunables();
    cSCPropertyHelp::GetPropertyValue(holder, kTuningPropertyDecayRate, t.decayRate);
    cSCPropertyHelp::GetPropertyValue(holder, kTuningPropertyLevelTolerance, t.levelToleranceThreshold);
    cSCPropertyHelp::GetPropertyValue(holder, kTuningPropertyMaxTakePerMonth, t.maxGarbageToTakePerMonth);
    // The original stores the raw uint32 into 0x100afdffc; the field is read as an int32 by the zone.
    std::uint32_t takePerTile = static_cast<std::uint32_t>(t.maxGarbageToTakePerMonthPerTile);
    if (cSCPropertyHelp::GetPropertyValue(holder, kTuningPropertyMaxTakePerMonthPerTile, takePerTile)) {
        t.maxGarbageToTakePerMonthPerTile = static_cast<std::int32_t>(takePerTile);
    }
    cSCPropertyHelp::GetPropertyValue(holder, kTuningPropertyMaxDecayPerMonthPerZone,
                                      t.maxGarbageToDecayPerMonthPerZone);
    cSCPropertyHelp::GetPropertyValue(holder, kTuningPropertyDefaultTileCost, t.defaultLandfillTileCost);
    cSCPropertyHelp::GetPropertyValue(holder, kTuningPropertyCostPerCellHeight, t.costPerCellHeightChange);
    cSCPropertyHelp::GetPropertyValue(holder, kTuningPropertyMoveWithTerrain, t.moveWithTerrain);
}

