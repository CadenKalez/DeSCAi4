// @ 0x100061236 (the +8 thunk is 0x100061b10). Always true; an unknown type is ignored.
bool cSC4LandfillDeveloper::DoMessage(cIGZMessage2* message) {
    if (!message) return true;
    const std::uint32_t type = message->GetType();
    auto* standard = static_cast<cIGZMessage2Standard*>(message);

    if (type == kLandfillMessageViewLevel) {                    // 0xc6cdbf1a
        if (zones_.empty()) return true;
        const std::uint32_t level = g_host ? g_host->ViewLevel() : 0;
        for (cSC4LandfillZone* zone : zones_) {
            ILandfillEffect* flock = zone->Seagulls();          // +0x78
            if (!flock) continue;
            const bool running = flock->IsRunning();            // vslot 0x28
            if (level == 1) {
                if (!running) flock->Start(0);                  // vslot 0x18
            } else if (running) {
                flock->Stop(true);                             // vslot 0x20
            }
        }
    } else if (type == kLandfillMessageZoneChange) {            // 0x07699455
        auto* region = static_cast<const LandfillCellRegion*>(standard->GetVoid2());
        DoZoneChange(region, static_cast<std::uint32_t>(standard->GetData3()));
    } else if (type == kLandfillMessageFundsChanged) {          // 0x0772fad4
        if (!department_) return true;
        const float funding = department_->GetFundingPercentage();   // read once, before the loop
        for (cSC4LandfillZone* zone : zones_) {
            ILandfillEffect* generator = zone->TruckGenerator();     // +0x68
            if (generator) generator->SetEnabled(0.0f < funding);    // vslot 0xa0
        }
    } else if (type == kLandfillMessageCityInit) {              // 0x26d31ec1
        // The department only exists once the budget simulator is up; a second message overwrites the
        // pointer without releasing the old reference (original behaviour).
        department_ = budget_ ? budget_->GetDepartmentBudget(kLandfillBudgetDepartment) : nullptr;
        if (department_) department_->AddRef();
        if (pendingZoneInit_) {
            for (cSC4LandfillZone* zone : zones_) zone->Init();
            UpdateBudgetRequirements();
            UpdateCapacityValues();
        }
    } else if (type == kLandfillMessageTerrainChanged) {        // 0x278e6003
        if (zones_.empty()) return true;
        const std::uint32_t data1 = static_cast<std::uint32_t>(standard->GetData1());
        const std::uint32_t data2 = static_cast<std::uint32_t>(standard->GetData2());
        const std::uint32_t reason = static_cast<std::uint32_t>(standard->GetData4());
        LandfillRect rect;
        rect.x0 = static_cast<int>(data1 >> 16) - 1;
        rect.z0 = static_cast<int>(data2 >> 16) - 1;
        rect.x1 = static_cast<int>(data1 & 0xffff);
        rect.z1 = static_cast<int>(data2 & 0xffff);
        const int cellsX = city_ ? city_->CellCountX() : 0;
        const int cellsZ = city_ ? city_->CellCountZ() : 0;
        if ((data1 >> 16) == 0) rect.x0 = 0;
        if (cellsX <= rect.x1) rect.x1 = cellsX - 1;
        if ((data2 >> 16) == 0) rect.z0 = 0;
        if (cellsZ <= rect.z1) rect.z1 = cellsZ - 1;
        if (reason - 1u < 3u) DoTerrainChanged(rect);
    } else if (type == kLandfillMessageMonthlySimulation) {     // 0x66956816
        DoMonthlySimulation();
    }
    return true;
}

