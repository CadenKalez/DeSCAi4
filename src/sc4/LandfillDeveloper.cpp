// @ 0x1000610dc: uint16 version 3, int32 zone count, then every zone. The original ignores stream errors.
bool cSC4LandfillDeveloper::Write(cIGZOStream& stream) const {
    stream.SetUint16(static_cast<std::uint16_t>(kLandfillDeveloperStreamVersion));
    stream.SetSint32(static_cast<std::int32_t>(zones_.size()));
    for (cSC4LandfillZone* zone : zones_) zone->Write(stream);
    return true;
}

// @ 0x100061146: version 3 only. The +0x20 flag is armed before the version check, the list is cleared
// without releasing its zones (the original leaks them here as well), and a zone whose Read fails is leaked.
bool cSC4LandfillDeveloper::Read(cIGZIStream& stream) {
    pendingZoneInit_ = true;
    std::uint16_t version = 0;
    stream.GetUint16(version);
    if (version != kLandfillDeveloperStreamVersion) return false;
    std::int32_t count = 0;
    stream.GetSint32(count);
    zones_.clear();
    for (std::int32_t i = 0; i < count; ++i) {
        auto* zone = new cSC4LandfillZone(ZoneHostOrNull());
        zone->AddRef();
        if (zone->Read(stream)) zones_.push_front(zone);
    }
    return true;
}

