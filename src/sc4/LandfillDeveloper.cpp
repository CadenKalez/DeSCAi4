// @ 0x100062286: used = min(garbage, capacity), capacity = the total capacity.
void cSC4LandfillDeveloper::GetLandfillUsage(std::uint32_t& used, std::uint32_t& capacity) {
    capacity = capacity_;
    std::uint32_t value = garbage_;
    used = value;
    if (capacity < value) value = capacity;
    used = value;
}

