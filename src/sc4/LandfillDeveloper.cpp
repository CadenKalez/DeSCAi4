// @ 0x100060940 (inlined into GZCOM_CreatecSC4LandfillDeveloper): the list sentinel points at itself, the
// six service pointers / the maintenance cost / the capacity pair / the three flags are zeroed.
cSC4LandfillDeveloper::cSC4LandfillDeveloper() = default;

// The inlined destructor of FinalRelease (0x100060b53..0x100060b8c) only resets the three vptrs and clears
// the zone *nodes*; the zones themselves are released by Shutdown.
cSC4LandfillDeveloper::~cSC4LandfillDeveloper() { zones_.clear(); }

// @ 0x100060a94. iid 1 and the class iid select the primary view, 0x452294aa the message target (+8) and
// 0xe4fda3d4 the serializable (+0x10); the reference goes through the primary AddRef. The two non-virtual
// thunks (0x100060ad8 / 0x100060ae6) are generated by the compiler from the three bases.
bool cSC4LandfillDeveloper::QueryInterface(std::uint32_t iid, void** out) {
    if (!out) return false;
    if (iid == kGZIID_cIGZUnknown || iid == kGZIID_cISC4LandfillDeveloper) {
        *out = static_cast<cISC4LandfillDeveloper*>(this);
    } else if (iid == kLandfillMessageTargetIid) {
        *out = static_cast<cIGZMessageTarget2*>(this);
    } else if (iid == kLandfillSerializableIid) {
        *out = static_cast<cIGZSerializable*>(this);
    } else {
        return false;
    }
    AddRef();
    return true;
}

// @ 0x100060af4 (+ the two thunks 0x100060b02 / 0x100060b10, all +0x1c).
std::uint32_t cSC4LandfillDeveloper::AddRef() { return ++refCount_; }

// @ 0x100060b1e (+ the thunks 0x100060b98 / 0x100060c02): the count is *not* decremented when the object dies.
std::uint32_t cSC4LandfillDeveloper::Release() {
    if (1 < refCount_) return --refCount_;
    FinalRelease();
    return 0;
}

// @ 0x100060b3a: virtual Shutdown, then the inlined destructor and operator delete.
void cSC4LandfillDeveloper::FinalRelease() {
    Shutdown();
    delete this;
}

